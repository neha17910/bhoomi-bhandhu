export function isValidLanguageCode(value: unknown): value is LanguageCode {
  return (
    typeof value === "string" &&
    SUPPORTED_LANGUAGES.some((lang) => lang.code === value)
  );
}

export function getLanguageOption(code: LanguageCode): LanguageOption {
  return (
    SUPPORTED_LANGUAGES.find((lang) => lang.code === code) ??
    SUPPORTED_LANGUAGES[0]
  );
}

export function translate(code: LanguageCode, key: TranslationKey): string {
  return TRANSLATIONS[code]?.[key] ?? TRANSLATIONS.en[key] ?? key;
}
